-- 직원 알림 재시도 큐(L14, ADR-0058). 알림 DB에 알림을 저장하지 못했을 때 세션 DB에 남겨 두었다가 복구 뒤 다시 저장·전달한다(Trace outbox와 같은 구조, D16).
-- turn_id가 없는 알림은 ''로 저장한다(UNIQUE가 NULL을 서로 다른 값으로 보지 않게). 전달이 끝나면 행을 지운다.
CREATE TABLE IF NOT EXISTS alert_queue (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id      TEXT NOT NULL,
  turn_id         TEXT NOT NULL DEFAULT '',
  kind            TEXT NOT NULL,
  rule_id         TEXT,
  pause_reason    TEXT,
  attempts        INTEGER NOT NULL DEFAULT 0,
  next_attempt_at DOUBLE PRECISION NOT NULL DEFAULT 0,
  last_error      TEXT,
  created_at      DOUBLE PRECISION NOT NULL,
  UNIQUE (session_id, turn_id, kind)
);
CREATE INDEX IF NOT EXISTS alert_queue_due ON alert_queue(next_attempt_at, id);
